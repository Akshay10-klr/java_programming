package corepack;

public class EscapeSequences {

	public static void main(String[] args) {
//		Adds a space between words
		System.out.println("Luminar\tTechnolab");
//		prints in two lines
		System.out.println("Luminar\nTechnolab");
//		Adds a Quote between words
		System.out.println("Luminar\'Technolab");
//		Adds double quotes between words
		System.out.println("Luminar\"Technolab");
//		Adds slash between words
		System.out.println("Luminar\\Technolab");

		}

}
