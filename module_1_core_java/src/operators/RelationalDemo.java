package operators;

public class RelationalDemo {

	public static void main(String[] args) {

		int i=10,j=25;
		System.out.println("the first number is "+i+"\nsecond number is "+j);
		System.out.println("numberone == numbertwo\t"+(i==j));
		System.out.println("numberone != numbertwo\t"+(i!=j));
		System.out.println("numberone <= numbertwo\t"+(i<=j));
		System.out.println("numberone >= numbertwo\t"+(i>=j));
		System.out.println("numberone > numbertwo\t"+(i>j));
		System.out.println("numberone < numbertwo\t"+(i<j));


		
	}

}
